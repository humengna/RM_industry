# coding: utf-8
"""
沪深300 五均线四级发散策略 —— 本地回测参数。

原始脚本是 QMT 内置 Python 版（ContextInfo + passorder），这里改写成
xtdata 取数 + 自带撮合引擎的本地回测版，参数与选股逻辑保持一致。
"""

# ============================================================
# 股票池
# ============================================================
INDEX_CODE = '000300.SH'      # 沪深300 指数代码，同时用作交易日历
INDEX_SECTOR = '沪深300'       # xtdata 板块名
# 成分股按"当时"取（point-in-time），避免用今天的成分股回测历史造成幸存者偏差。
# 'month' = 按月取一次再前向填充（沪深300 每年 6/12 月调整两次，月度足够）
# 'day'   = 每个交易日都查一次，最精确但慢很多
CONSTITUENT_GRANULARITY = 'month'
# 历史成分股缓存文件（CSV: date,stock）。第一次跑会自动生成，之后离线复用
CONSTITUENT_CACHE = 'data/hs300_constituents.csv'
# 取不到历史成分股时是否允许退回"当前成分股"。默认 False：宁可报错也不做带偏差的回测
ALLOW_CURRENT_CONSTITUENTS_FALLBACK = False


# ============================================================
# 均线与选股
# ============================================================
MA_PERIODS = (5, 10, 20, 30, 60)
HISTORY_COUNT = max(MA_PERIODS) + 1     # 至少需要的历史长度

MAX_HOLDINGS = 2                        # 最大持仓数
TARGET_WEIGHT = 1.0 / MAX_HOLDINGS      # 单股目标仓位 = 1 / 持仓数
# 单只票的仓位上限（按下单时的总资产算）。持仓数少时这条才真正起作用：
# MAX_HOLDINGS=2 -> TARGET_WEIGHT=50%，与上限一致；
# 若把 MAX_HOLDINGS 调成 1，仓位仍被这条限制在 50%，另一半留现金。
MAX_POSITION_WEIGHT = 0.50

# 候选排序方向。
# 原脚本里 results.sort(key=..., #reverse=True) 的 reverse 被注释掉了，
# 实际是"按总发散度从小到大"取前 5，与注释文字相反。
# 这里保持原脚本的真实行为；想按发散度从大到小取，改成 False。
SORT_ASCENDING = True


# ============================================================
# 回测区间与账户
# ============================================================
START_DATE = '20230101'
END_DATE = '20241231'
INIT_CASH = 1000000.0
LOT_SIZE = 100
CASH_BUFFER = 0.98            # 下单金额留 2% 余量，与原脚本一致


# ============================================================
# 交易成本
# ============================================================
COMMISSION_RATE = 0.0001      # 佣金万 1，双边
MIN_COMMISSION = 5.0          # 单笔最低佣金
STAMP_TAX_RATE = 0.0005       # 印花税千 0.5，仅卖出（2023-08-28 起减半）
TRANSFER_FEE_RATE = 0.00001   # 过户费万 0.1，双边
SLIPPAGE = 0.0                # 滑点（按成交价比例），0 = 不计


# ============================================================
# 撮合假设
# ============================================================
# T 日收盘算信号，T+1 开盘成交（对应原脚本 quickTrade=0：下一根K线首个 tick 触发）
EXECUTION_PRICE = 'open'
# 一字涨停买不进、一字跌停卖不掉
RESPECT_PRICE_LIMITS = True
# T+1：当日买入次日才可卖
T_PLUS_1 = True


# ============================================================
# 行情
# ============================================================
PERIOD = '1d'
# xtdata 的复权方式：none / front / back / front_ratio / back_ratio
# 原脚本用的是 QMT 专有的 'follow'（跟随客户端设置），xtdata 没有对应值，
# 这里用前复权，保证均线不被除权跳空污染
DIVIDEND_TYPE = 'front'
FIELDS = ('time', 'open', 'high', 'low', 'close', 'volume', 'amount')
# 取数分批大小，股票太多时一次性请求容易超时
BATCH_SIZE = 200


# ============================================================
# 输出
# ============================================================
OUTPUT_DIR = 'backtests'      # 每次回测生成一个带时间戳的子目录
PRINT_DAILY = True            # 打印每日选股与成交
PRINT_ALL_CANDIDATES = False  # 打印全部候选（否则只打印前 MAX_HOLDINGS）
